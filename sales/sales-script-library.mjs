export const scriptCategories = [
  'Nursing Homes / Senior Living',
  'Town Halls / Municipalities',
  'Schools / Education',
  'Hospitals / Health Systems',
  'Intro & Voicemail',
  'Follow-Up & Objections',
  'Closing & Next Steps',
];

const [seniorLiving, municipalities, education, healthSystems, introductions, followUps, closing] = scriptCategories;
const counter = 'A visitor can scan a QR code, open a board in a browser, and tap picture-and-word choices to speak a request.';
const bedside = 'In the TinkyStroke walkthrough, a person can choose a picture-and-word response to a care conversation and have their device speak it aloud.';
const classroom = 'A TinkySpeak classroom board gives students picture-and-word choices they can use and speak during a familiar routine.';
const language = 'Show a supported language using the live board and let the person choose the words they want spoken.';

function makeScript(entry) {
  const value = entry.value || counter;
  const greeting = 'Hi {{FirstName}}, this is {{YourName}} with TinkyTown.';
  const signature = '{{YourName}}\nTinkyTown';
  return {
    id: entry.id,
    title: entry.title,
    category: entry.category,
    description: entry.description,
    channels: entry.channels || ['phone', 'email', 'voicemail'],
    emailSubject: entry.emailSubject,
    versions: {
      script: [
        'Opening (30 seconds)\n' + greeting + ' ' + entry.opening,
        'Value (30–60 seconds)\n' + value + ' ' + entry.example,
        'What to demonstrate\n' + entry.demonstrate + '\n' + entry.question,
        'Close (30 seconds)\n' + entry.next,
      ].join('\n\n'),
      email: [
        'Hi {{FirstName}},', entry.opening, value + ' ' + entry.example, entry.next, signature,
      ].join('\n\n'),
      voicemail: [
        greeting, entry.example, entry.next, 'You can reach me at {{Phone}}. Thanks for your time.',
      ].join(' '),
      talking: [
        'Start with their workflow\n' + entry.question,
        'Show the interaction\n' + entry.demonstrate,
        'Agree on a next step\n' + entry.next,
      ].join('\n\n'),
      objections: [
        '“' + entry.objection + '”',
        entry.response,
        'Return to their situation\n' + entry.question,
      ].join('\n\n'),
      followup: [
        'Hi {{FirstName}},',
        'I wanted to follow up with one idea for {{Organization}}. ' + entry.example,
        entry.followup || entry.next,
        signature,
      ].join('\n\n'),
    },
  };
}

