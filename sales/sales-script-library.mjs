const [seniorLiving, municipalities, education, healthSystems, introductions, followUps, closing, visits] = scriptCategories;

function makeScript(entry) {
  const greeting = 'Hi, I’m {{YourName}} with TinkyTown.';
  const signature = '{{YourName}}\nTinkyTown';
  return {
    id: entry.id, title: entry.title, category: entry.category, description: entry.description,
    channels: entry.channels, emailSubject: entry.emailSubject,
    versions: {
      script: entry.script || ['Start the conversation\n' + greeting + ' ' + entry.opening,
        'Hear their answer\n' + entry.question, 'Offer an example\n' + entry.show,
        'Ask, then pause\n' + entry.next].join('\n\n'),
      email: ['Hi {{FirstName}},', entry.emailOpening, entry.emailAsk || entry.followup, signature].join('\n\n'),
      voicemail: 'Hi {{FirstName}}, it’s {{YourName}} with TinkyTown. ' + entry.voicemail + ' My number is {{Phone}}. Thanks.',
      talking: ['Listen for\n' + entry.question, 'During the visit\n' + entry.demonstrate,
        'Before you leave\n' + entry.next].join('\n\n'),
      objections: 'Buyer\n“' + entry.objection + '”\n\nYou\n“' + entry.response + '”',
      followup: ['Hi {{FirstName}},', entry.followup, signature].join('\n\n'),
    },
  };
}

