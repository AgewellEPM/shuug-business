"""Extract pinned IRS 2023/2024 tax tables and computation worksheets.

Requires Poppler pdftotext. Reads the published numbers, not a reconstruction
from brackets. Each table must have all 2,062 contiguous intervals and match
the IRS worked example. Input PDFs are pinned before parsing.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET

PINS = {
    2023: ("d3d2ad3a1f167a3a9db369fecc2faa4b15b94ec6918e7263db00eac95e066ed4", 2599),
    2024: ("fb82d748af260815c65e50591ec69cfb566e9c71ea7589abee06ac7de9a7be09", 2575),
}
STATUSES = dict(zip("ABCD", ["single", "marriedJoint", "marriedSeparate", "headOfHousehold"]))


def extract(pdf, year):
    raw = pdf.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != PINS[year][0]:
        raise ValueError("IRS source changed; independently review and pin it before import.")
    xml = subprocess.run(["pdftotext", "-bbox", str(pdf), "-"], capture_output=True, check=True).stdout
    pages = ET.fromstring(xml).findall(".//{*}page")
    rows = []
    for index, page in enumerate(pages[2:14], 2):
        words = [word for word in page.findall(".//{*}word")
                 if re.fullmatch(r"\d[\d,]*", word.text or "")
                 and (index != 2 or float(word.attrib["yMin"]) > 245)]
        for left, right in [(40, 217), (217, 394), (394, 578)]:
            grouped = []
            for word in sorted((word for word in words if left <= float(word.attrib["xMin"]) < right),
                               key=lambda word: float(word.attrib["yMin"])):
                y = float(word.attrib["yMin"])
                if not grouped or y - grouped[-1][0] > 1:
                    grouped.append((y, []))
                grouped[-1][1].append(word)
            for _, group in grouped:
                if len(group) == 6:
                    rows.append([int(word.text.replace(",", "")) for word in
                                 sorted(group, key=lambda word: float(word.attrib["xMin"]))])
    rows.sort()
    end = 0
    for row in rows:
        if row[0] != end or row[1] <= end or any(value < 0 for value in row):
            raise ValueError("Missing, duplicate or invalid published tax-table interval.")
        end = row[1]
    if len(rows) != 2062 or end != 100000 or next(row for row in rows if row[0] == 25300)[3] != PINS[year][1]:
        raise ValueError("The table count, boundaries or published worked example differ.")
    text = subprocess.run(["pdftotext", "-layout", str(pdf), "-"], capture_output=True, check=True).stdout.decode()
    worksheet = text.split(f"{year} Tax Computation Worksheet—Line 16", 1)[1].split(f"{year} Earned Income Credit", 1)[0]
    result, status = {}, None
    for line in worksheet.splitlines():
        if match := re.match(r"Section ([ABCD])—", line):
            status = STATUSES[match[1]]
            result[status] = []
        if not line.startswith(("At least $", "Over $")):
            continue
        ceiling = re.search(r"but not over \$([\d,]+)", line)
        amounts = re.search(r"× (\d+)%.*\$\s*\$ ([\d,]+)\.(\d{2})", line)
        if not status or not amounts:
            raise ValueError("A published computation row was not parsed exactly.")
        result[status].append([int(ceiling[1].replace(",", "")) if ceiling else None,
                               int(amounts[1]), int(amounts[2].replace(",", "")) * 100 + int(amounts[3])])
    if set(result) != set(STATUSES.values()):
        raise ValueError("Missing filing-status computation worksheet.")
    for key, values in result.items():
        expected = 5 if year == 2024 or key == "marriedJoint" else 4
        if len(values) != expected or values[-1][0] is not None or values[-1][1] != 37:
            raise ValueError("Incomplete computation worksheet.")
        if [value[0] for value in values[:-1]] != sorted(value[0] for value in values[:-1]):
            raise ValueError("Unordered computation worksheet.")
    return rows, result, digest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("year", type=int, choices=PINS)
    parser.add_argument("pdf", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    rows, worksheets, digest = extract(args.pdf, args.year)
    source = {"taxYear": args.year, "url": f"https://www.irs.gov/pub/irs-prior/i1040tt--{args.year}.pdf",
              "pdfSha256": digest, "rows": len(rows), "workedExampleJointTaxDollars": PINS[args.year][1],
              "columns": ["atLeast", "lessThan", "single", "marriedJoint", "marriedSeparate", "headOfHousehold"]}
    lines = [", ".join(json.dumps(row, separators=(",", ":")) for row in rows[index:index + 8])
             for index in range(0, len(rows), 8)]
    output = f"// Published IRS {args.year} numbers; generated by scripts/tax/import_prior_tax_tables.py.\n"
    output += f"export const taxTable{args.year}=Object.freeze([\n  " + ",\n  ".join(lines) + "\n].map(Object.freeze));\n"
    output += f"export const taxComputation{args.year}=Object.freeze(Object.fromEntries(Object.entries(" + json.dumps(worksheets, separators=(",", ":")) + ").map(([key,rows])=>[key,Object.freeze(rows.map(Object.freeze))])));\n"
    output += "export const taxTableSource=Object.freeze(" + json.dumps(source, separators=(",", ":")) + ");\n"
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output)
    print(json.dumps(source))


if __name__ == "__main__":
    main()
