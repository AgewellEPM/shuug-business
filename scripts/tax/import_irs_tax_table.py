"""Import the official 2025 1040 table from a previously downloaded IRS HTML page.

No tax values are reconstructed from brackets. Require the complete published
table, contiguous intervals and the IRS's own married-joint worked example.
"""
import argparse
import hashlib
from html.parser import HTMLParser
import json
from pathlib import Path
import re


class Tables(HTMLParser):
    def __init__(self):
        super().__init__()
        self.tables, self.stack, self.row, self.cell = [], [], [], None

    def handle_starttag(self, tag, attrs):
        if tag == "table": self.stack.append([])
        if self.stack and tag == "tr": self.row = []
        if self.stack and tag in ("td", "th"): self.cell = []

    def handle_data(self, value):
        if self.cell is not None: self.cell.append(value)

    def handle_endtag(self, tag):
        if tag in ("td", "th") and self.cell is not None:
            self.row.append(" ".join("".join(self.cell).split()))
            self.cell = None
        if tag == "tr" and self.stack: self.stack[-1].append(self.row)
        if tag == "table" and self.stack: self.tables.append(self.stack.pop())


def main():
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument("html", type=Path)
    args.add_argument("output", type=Path)
    selected = args.parse_args()
    raw = selected.html.read_bytes()
    html = raw.decode("utf-8")
    if not re.search(r"2025\s+Tax\s+Table", re.sub(r"<[^>]*>", " ", html)):
        raise ValueError("The input does not explicitly identify the 2025 tax table.")
    parser = Tables()
    parser.feed(html)
    candidates = []
    for table in parser.tables:
        rows = [[int(value.replace(",", "")) for value in row] for row in table
                if len(row) == 6 and all(re.fullmatch(r"[0-9,]+", value) for value in row)]
        if len(rows) > 2000: candidates.append(rows)
    if len(candidates) != 1: raise ValueError("Expected one complete published tax table.")
    rows = candidates[0]
    end = 0
    for row in rows:
        if row[0] != end or row[1] <= end or any(value < 0 for value in row):
            raise ValueError("The tax table is incomplete, duplicated or out of order.")
        end = row[1]
    if end != 100000 or next(row for row in rows if row[0] == 25300)[3] != 2562:
        raise ValueError("The published table boundaries/worked example do not match 2025.")
    source = {"taxYear": 2025, "url": "https://www.irs.gov/instructions/i1040gi",
              "htmlSha256": hashlib.sha256(raw).hexdigest(), "rows": len(rows),
              "columns": ["atLeast", "lessThan", "single", "marriedJoint", "marriedSeparate", "headOfHousehold"]}
    selected.output.parent.mkdir(parents=True, exist_ok=True)
    lines = [", ".join(json.dumps(row, separators=(",", ":")) for row in rows[index:index + 8])
             for index in range(0, len(rows), 8)]
    selected.output.write_text("// Official IRS 2025 table; generated by scripts/tax/import_irs_tax_table.py.\n"
                               "export const taxTable2025 = Object.freeze([\n  " + ",\n  ".join(lines)
                               + "\n].map(row => Object.freeze(row)));\nexport const taxTableSource = Object.freeze("
                               + json.dumps(source, separators=(",", ":")) + ");\n")
    print(json.dumps(source))


if __name__ == "__main__": main()
