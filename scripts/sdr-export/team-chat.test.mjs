import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { DatabaseSync } from 'node:sqlite';
import { test } from 'node:test';
import { teamChat } from './team-chat.mjs';

test('channel history pages meet without gaps and each reader advances independently', t => {
  const db = new DatabaseSync(':memory:');
  const chat = teamChat(db);
  t.after(() => { chat.close(); db.close(); });
  const owner = { id: 'owner', name: 'Workspace owner', role: 'owner' };
  const rep = { id: '12', name: 'Sales rep', role: 'agent' };
  const send = (user, channel, body) => chat.dispatch(user, 'chat-send', { channel, body, requestId: randomUUID() }).id;
  const ids = Array.from({ length: 105 }, (_, index) => {
    send(rep, 'wins', 'Another channel');
    return send(index % 2 ? rep : owner, 'general', 'Message ' + index);
  });
  const sync = (user, options = {}) => chat.dispatch(user, 'chat-sync', { channel: 'general', ...options });
  const last = sync(rep);
  assert.deepEqual(last.messages.map(r => r.id), ids.slice(-50));
  assert.equal(last.hasMore, true);
  const prior = chat.dispatch(rep, 'chat-history', { channel: 'general', before: last.messages[0].id });
  const first = chat.dispatch(rep, 'chat-history', { channel: 'general', before: prior.messages[0].id });
  assert.equal(first.hasMore, false);
  assert.deepEqual([...first.messages, ...prior.messages, ...last.messages].map(r => r.id), ids);
  const forward = sync(rep, { after: 0 });
  assert.deepEqual(forward.messages.map(r => r.id), ids.slice(0, 50));
  assert.deepEqual(sync(rep, { after: forward.messages.at(-1).id }).messages.map(r => r.id), ids.slice(50, 100));
  const general = user => sync(user).channels.find(c => c.slug === 'general');
  assert.deepEqual([general(owner).unread, general(rep).unread], [52, 53]);
  chat.dispatch(rep, 'chat-seen', { channel: 'general', through: ids[30] });
  chat.dispatch(rep, 'chat-seen', { channel: 'general', through: ids[1] });
  assert.equal(general(rep).seen, ids[30]);
  assert.equal(general(rep).unread, 37);
  assert.equal(general(owner).unread, 52);
  assert.throws(() => chat.dispatch(rep, 'chat-seen', { channel: 'wins', through: ids[30] }), { status: 404 });
  assert.throws(() => chat.dispatch({ ...rep, role: 'location' }, 'chat-sync', {}), { status: 403 });
  for (const body of ['   ', 'x'.repeat(2001)]) assert.throws(() => send(rep, 'general', body), { status: 400 });
  const request = { channel: 'general', body: 'Original', requestId: randomUUID() };
  chat.dispatch(rep, 'chat-send', request);
  assert.throws(() => chat.dispatch(rep, 'chat-send', { ...request, body: 'Changed' }), { status: 409 });
});

test('private activity changes only participant inboxes and never writes to legacy channel tables', t => {
  const db = new DatabaseSync(':memory:'), chat = teamChat(db);
  t.after(() => { chat.close(); db.close(); });
  const people = [{id:'owner', name:'Owner'}, {id:'2', name:'Ari'}, {id:'12', name:'Sam'}, {id:'4', name:'Alex'}];
  const call = (id, action, input = {}) => chat.dispatch({ ...people.find(p => p.id === id), role: id === 'owner' ? 'owner' : 'agent' }, action, input, undefined, () => people);
  const outside = call('owner', 'chat-sync').version;
  const { slug } = call('2', 'chat-direct-open', {memberId:'12'});
  assert.deepEqual(call('12', 'chat-sync').directs, []);
  assert.throws(() => call('2', 'chat-direct-open', {memberId:'2'}), { status:404 });
  const request = {channel:slug, body:'Private handoff', requestId:randomUUID()};
  const sent = call('2', 'chat-send', request);
  assert.deepEqual(call('2', 'chat-send', request), sent);
  assert.equal(call('12', 'chat-direct-open', {memberId:'2'}).slug, slug);
  assert.equal(call('12', 'chat-sync').directs[0].unread, 1);
  call('12', 'chat-seen', {channel:slug, through:sent.id});
  assert.equal(call('12', 'chat-sync').directs[0].unread, 0);
  assert.equal(call('owner', 'chat-sync').version, outside);
  assert.equal(call('4', 'chat-sync').directs.length, 0);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM chat_messages').get().n, 0);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM chat_channels WHERE slug = ?').get(slug).n, 0);
});

test('online staff follow live sessions, expire, and use current directory permissions', async t => {
  let now = 10_000;
  const db = new DatabaseSync(':memory:'), chat = teamChat(db, { now: () => now });
  t.after(() => { chat.close(); db.close(); });
  const owner = { id: 'owner', role: 'owner', name: 'Owner' };
  const rep = { id: '7', role: 'agent', name: 'Rep' };
  let active = true;
  const directory = () => [{ id: owner.id, name: 'Workspace owner' }, ...(active ? [{ id: rep.id, name: 'Alex' }] : [])];
  const read = () => chat.dispatch(owner, 'chat-sync', {}, undefined, directory);
  chat.presence.touch('owner-browser', owner);
  const { version } = read();
  const watching = chat.dispatch(owner, 'chat-watch', { version });
  chat.presence.touch('rep-phone', rep);
  await watching;
  assert.deepEqual(read().online.map(member => member.name), ['Alex', 'Workspace owner']);
  const connected = read().version;
  chat.presence.touch('rep-laptop', rep);
  chat.presence.leave('rep-phone');
  chat.presence.touch('rep-phone', rep);
  assert.equal(read().version, connected);
  assert.deepEqual(read().online[0], { id: '7', name: 'Alex' });
  active = false;
  assert.deepEqual(read().online.map(member => member.id), ['owner']);
  active = true;
  now += 100_000;
  chat.presence.touch('owner-browser', owner);
  now += 20_001;
  assert.deepEqual(read().online.map(member => member.id), ['owner']);
  chat.presence.touch('rep-laptop', rep);
  chat.presence.leave('rep-laptop');
  chat.presence.touch('facility-browser', { id: '7', role: 'location' });
  assert.deepEqual(read().online.map(member => member.id), ['owner']);
});
