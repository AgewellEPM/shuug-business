import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,writeFileSync,readFileSync,statSync,rmSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {createFirmBundle,unlockFirmBundle,signEnrollmentRequest,recoverFirmObject} from '../firm-recovery.mjs';
import {generateRecipientKeyPair,publicKeyId,sealEnvelope,verifyEnrollmentManifest} from '../envelope.mjs';
const pass='synthetic test only long recovery passphrase 789';
test('encrypted offhost keys sign client-bound manifests and recover a real encrypted object without server private keys',async()=>{
 const {bundle,publicPins}=await createFirmBundle('synthetic-workspace',pass);
 assert(!JSON.stringify(bundle).includes('"d":'));
 const unlocked=await unlockFirmBundle(bundle,pass,publicPins);
 assert.equal(unlocked.signing.extractable,false);assert.equal(unlocked.recovery.extractable,false);
 const client=await generateRecipientKeyPair();
 const request={version:1,workspaceId:'synthetic-workspace',accountId:'synthetic-account',clientId:'synthetic-client',client:{keyId:await publicKeyId(client.publicKey),publicKey:client.publicKey}};
 const manifest=await signEnrollmentRequest(request,unlocked,{epoch:1});
 const expected={accountId:request.accountId,clientId:request.clientId,minimumEpoch:1,objectId:crypto.randomUUID(),revision:1,domain:'tax-identity'};
 const verified=await verifyEnrollmentManifest(manifest,expected,publicPins);
 const text=new TextEncoder().encode('Synthetic SSN 000-12-3456; never a real client');
 const envelope=await sealEnvelope(text,{workspaceId:request.workspaceId,accountId:request.accountId,objectId:expected.objectId,revision:1,domain:expected.domain},verified.recipients,'client',client.privateKey);
 assert.deepEqual(await recoverFirmObject(envelope,manifest,unlocked,expected),text);
 await assert.rejects(()=>recoverFirmObject(envelope,manifest,unlocked,{...expected,accountId:'foreign-account'}));
 await assert.rejects(()=>recoverFirmObject(envelope,manifest,unlocked,{...expected,objectId:'wrong-object'}));
 await assert.rejects(()=>signEnrollmentRequest({...request,workspaceId:'wrong-workspace'},unlocked,{epoch:1}));
 await assert.rejects(()=>signEnrollmentRequest(request,unlocked,{epoch:0}));
 await assert.rejects(()=>unlockFirmBundle(bundle,'incorrect but long passphrase 123',publicPins));
 await assert.rejects(()=>unlockFirmBundle(bundle,pass,{...publicPins,workspaceId:'wrong-workspace'}));
 const tampered={...bundle,ciphertext:bundle.ciphertext.slice(0,-2)+'AA'};
 await assert.rejects(()=>unlockFirmBundle(tampered,pass,publicPins));
 await assert.rejects(()=>unlockFirmBundle({...bundle,iterations:1},pass,publicPins));
 const past=Date.now()-3*86400000;
 const expired=await signEnrollmentRequest(request,unlocked,{epoch:1,validDays:1,now:past});
 await assert.rejects(()=>recoverFirmObject(envelope,expired,unlocked,expected));
 assert.deepEqual(await recoverFirmObject(envelope,expired,unlocked,{...expected,manifestId:expired.manifestId,archiveValidAt:new Date(past+1000).toISOString()}),text);
 await assert.rejects(()=>recoverFirmObject(envelope,expired,unlocked,{...expected,manifestId:'wrong-manifest',archiveValidAt:new Date(past+1000).toISOString()}));
});
test('offline CLI requires offhost acknowledgement, writes private exclusive files and recovers only explicit input',async()=>{
 const directory=mkdtempSync(path.join(tmpdir(),'synthetic-firm-recovery-'));
 const file=n=>path.join(directory,n),cli=fileURLToPath(new URL('../offline-cli.mjs',import.meta.url));
 const run=(args,input=pass+'\n')=>spawnSync(process.execPath,[cli,...args],{input,encoding:'utf8',maxBuffer:4096});
 const common=['--confirm-off-host','--passphrase-fd','0','--bundle',file('bundle.json'),'--public-pins',file('pins.json')];
 try{
  assert.equal(run(['init','--workspace-id','synthetic-workspace']).status,1);
  writeFileSync(file('existing-pins.json'),'existing operator file');
  assert.equal(run(['init','--confirm-off-host','--passphrase-fd','0','--workspace-id','synthetic-workspace','--bundle',file('failed-bundle.json'),'--public-pins',file('existing-pins.json')]).status,1);
  assert.equal(existsSync(file('failed-bundle.json')),false);assert.equal(readFileSync(file('existing-pins.json'),'utf8'),'existing operator file');
  assert.equal(run(['init',...common,'--workspace-id','synthetic-workspace']).status,0);
  assert.equal(statSync(file('bundle.json')).mode&0o777,0o600);
  const original=readFileSync(file('bundle.json'),'utf8');
  assert.equal(run(['init',...common,'--workspace-id','synthetic-workspace']).status,1);assert.equal(readFileSync(file('bundle.json'),'utf8'),original);
  const client=await generateRecipientKeyPair(),pins=JSON.parse(readFileSync(file('pins.json'),'utf8'));
  const request={version:1,workspaceId:pins.workspaceId,accountId:'synthetic-account',clientId:'synthetic-client',client:{keyId:await publicKeyId(client.publicKey),publicKey:client.publicKey}};
  writeFileSync(file('request.json'),JSON.stringify(request));
  assert.equal(run(['sign',...common,'--request',file('request.json'),'--epoch','1','--out',file('manifest.json')]).status,0);
  const manifest=JSON.parse(readFileSync(file('manifest.json'),'utf8'));
  const expected={accountId:request.accountId,clientId:request.clientId,minimumEpoch:1,objectId:crypto.randomUUID(),revision:1,domain:'tax-identity'};
  const plain=new TextEncoder().encode('Synthetic recovered tax bytes');
  const envelope=await sealEnvelope(plain,{workspaceId:pins.workspaceId,accountId:request.accountId,objectId:expected.objectId,revision:1,domain:expected.domain},{clientPublicKey:client.publicKey,firmRecoveryPublicKey:pins.firmRecoveryPublicKey},'client',client.privateKey);
  writeFileSync(file('envelope.json'),JSON.stringify(envelope));writeFileSync(file('expected.json'),JSON.stringify(expected));
  const recovery=['recover',...common,'--manifest',file('manifest.json'),'--envelope',file('envelope.json'),'--expected',file('expected.json'),'--out',file('recovered.bin')];
  const result=run(recovery);assert.equal(result.status,0,result.stderr);assert(!result.stdout.includes('Synthetic recovered'));
  assert.deepEqual(new Uint8Array(readFileSync(file('recovered.bin'))),plain);assert.equal(statSync(file('recovered.bin')).mode&0o777,0o600);
  assert.equal(run(recovery).status,1);
 }finally{rmSync(directory,{recursive:true,force:true});}
});
